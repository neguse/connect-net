package main

import (
	"fmt"
	"path/filepath"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// Wrapper fields surface in C# as nullable primitives, so their value is written directly.
var wrapperKinds = map[protoreflect.FullName]protoreflect.Kind{
	"google.protobuf.DoubleValue": protoreflect.DoubleKind,
	"google.protobuf.FloatValue":  protoreflect.FloatKind,
	"google.protobuf.Int64Value":  protoreflect.Int64Kind,
	"google.protobuf.UInt64Value": protoreflect.Uint64Kind,
	"google.protobuf.Int32Value":  protoreflect.Int32Kind,
	"google.protobuf.UInt32Value": protoreflect.Uint32Kind,
	"google.protobuf.BoolValue":   protoreflect.BoolKind,
	"google.protobuf.StringValue": protoreflect.StringKind,
	"google.protobuf.BytesValue":  protoreflect.BytesKind,
}

// NullValue serializes as a JSON null, which the generated writers do not model. Messages using
// it, or repeated and map wrappers, keep going through Google.Protobuf at run time, as do all
// well-known types.
const nullValueEnum = protoreflect.FullName("google.protobuf.NullValue")

func generateJSON(plugin *protogen.Plugin, file *protogen.File) {
	if file.Desc.Syntax() != protoreflect.Proto3 || len(file.Messages) == 0 {
		return
	}

	base := filepath.Base(file.Desc.Path())
	filename := strings.TrimSuffix(base, filepath.Ext(base)) + ".connect-json.cs"
	if dir := filepath.Dir(file.Desc.Path()); dir != "." && dir != "" {
		filename = dir + "/" + filename
	}

	g := plugin.NewGeneratedFile(filename, "")
	p := func(format string, args ...interface{}) {
		fmt.Fprintf(g, format+"\n", args...)
	}
	p("// Code generated by protoc-gen-connect-csharp. DO NOT EDIT.")
	p("#nullable disable")
	p("")
	ns := getCSharpNamespace(file.Desc)
	if ns != "" {
		p("namespace %s", ns)
		p("{")
	}
	for _, message := range file.Messages {
		generateJSONMessage(p, message)
	}
	if ns != "" {
		p("}")
	}
}

func generateJSONMessage(p func(string, ...interface{}), message *protogen.Message) {
	if message.Desc.IsMapEntry() {
		return
	}
	name := string(message.Desc.Name())
	if jsonEligible(message) {
		p("public sealed partial class %s : global::ConnectNet.IConnectJsonMessage", name)
		p("{")
		generateJSONMembers(p, message)
	} else {
		p("public sealed partial class %s", name)
		p("{")
	}

	var nested []*protogen.Message
	for _, m := range message.Messages {
		if !m.Desc.IsMapEntry() {
			nested = append(nested, m)
		}
	}
	if len(nested) > 0 {
		p("public static partial class Types")
		p("{")
		for _, m := range nested {
			generateJSONMessage(p, m)
		}
		p("}")
	}
	p("}")
}

func jsonEligible(message *protogen.Message) bool {
	for _, field := range message.Fields {
		desc := field.Desc
		if desc.IsMap() {
			desc = desc.MapValue()
		}
		if desc.Enum() != nil && desc.Enum().FullName() == nullValueEnum {
			return false
		}
		if desc.Message() != nil && (field.Desc.IsList() || field.Desc.IsMap()) {
			if _, wrapper := wrapperKinds[desc.Message().FullName()]; wrapper {
				return false
			}
		}
	}
	return true
}

func generateJSONMembers(p func(string, ...interface{}), message *protogen.Message) {
	enums := map[protoreflect.FullName]int{}
	var enumOrder []protoreflect.EnumDescriptor
	enumIndex := func(e protoreflect.EnumDescriptor) int {
		i, ok := enums[e.FullName()]
		if !ok {
			i = len(enumOrder)
			enums[e.FullName()] = i
			enumOrder = append(enumOrder, e)
		}
		return i
	}

	p("void global::ConnectNet.IConnectJsonMessage.WriteJson(global::System.Text.Json.Utf8JsonWriter writer, global::Google.Protobuf.JsonFormatter fallback)")
	p("{")
	p("writer.WriteStartObject();")
	for _, field := range message.Fields {
		prop := propertyName(field.Desc)
		p("if (%s)", jsonPresence(field))
		p("{")
		p("writer.WritePropertyName(__ConnectJson.F%d);", field.Desc.Number())
		switch {
		case field.Desc.IsMap():
			p("writer.WriteStartObject();")
			p("foreach (var entry in this.%s)", prop)
			p("{")
			p("global::ConnectNet.ConnectJson.WriteMapKey(writer, entry.Key);")
			p("%s", jsonWriteValue(field.Desc.MapValue(), "entry.Value", enumIndex))
			p("}")
			p("writer.WriteEndObject();")
		case field.Desc.IsList():
			p("writer.WriteStartArray();")
			p("foreach (var item in this.%s)", prop)
			p("{")
			p("%s", jsonWriteValue(field.Desc, "item", enumIndex))
			p("}")
			p("writer.WriteEndArray();")
		default:
			p("%s", jsonWriteValue(field.Desc, "this."+prop, enumIndex))
		}
		p("}")
	}
	p("writer.WriteEndObject();")
	p("}")
	p("")
	generateJSONReader(p, message, enumIndex)
	p("")
	p("private static class __ConnectJson")
	p("{")
	for _, field := range message.Fields {
		p("internal static readonly global::System.Text.Json.JsonEncodedText F%d = global::System.Text.Json.JsonEncodedText.Encode(%q);", field.Desc.Number(), field.Desc.JSONName())
		if string(field.Desc.Name()) != field.Desc.JSONName() {
			p("internal static readonly global::System.Text.Json.JsonEncodedText P%d = global::System.Text.Json.JsonEncodedText.Encode(%q);", field.Desc.Number(), string(field.Desc.Name()))
		}
	}
	for i, e := range enumOrder {
		generateJSONEnumWriter(p, i, e)
		generateJSONEnumReader(p, i, e)
	}
	p("}")
}

func generateJSONReader(p func(string, ...interface{}), message *protogen.Message, enumIndex func(protoreflect.EnumDescriptor) int) {
	const tokens = "global::System.Text.Json.JsonTokenType"

	// JSON may repeat a field, where the last value wins, but may set a oneof only once. That
	// includes the synthetic oneof behind a proto3 optional field.
	oneofSlots := map[*protogen.Oneof]int{}
	for _, field := range message.Fields {
		if field.Oneof != nil {
			if _, ok := oneofSlots[field.Oneof]; !ok {
				oneofSlots[field.Oneof] = len(oneofSlots)
			}
		}
	}

	p("void global::ConnectNet.IConnectJsonMessage.MergeJson(ref global::System.Text.Json.Utf8JsonReader reader, global::Google.Protobuf.JsonParser fallback)")
	p("{")
	p("global::ConnectNet.ConnectJson.ExpectToken(ref reader, %s.StartObject);", tokens)
	if len(oneofSlots) > 0 {
		p("global::System.Span<bool> seenOneofs = stackalloc bool[%d];", len(oneofSlots))
	}
	p("while (reader.Read() && reader.TokenType != %s.EndObject)", tokens)
	p("{")
	for _, field := range message.Fields {
		desc := field.Desc
		match := fmt.Sprintf("global::ConnectNet.ConnectJson.TextEquals(ref reader, __ConnectJson.F%d)", desc.Number())
		if string(desc.Name()) != desc.JSONName() {
			match += fmt.Sprintf(" || global::ConnectNet.ConnectJson.TextEquals(ref reader, __ConnectJson.P%d)", desc.Number())
		}
		p("if (%s)", match)
		p("{")
		if field.Oneof != nil {
			p("global::ConnectNet.ConnectJson.MarkOneofSeen(seenOneofs, %d);", oneofSlots[field.Oneof])
		}
		p("reader.Read();")
		if !isValueMessage(desc) || desc.IsList() || desc.IsMap() {
			p("if (reader.TokenType == %s.Null)", tokens)
			p("{")
			p("%s", jsonClear(field))
			p("continue;")
			p("}")
		}
		prop := "this." + propertyName(desc)
		switch {
		case desc.IsMap():
			p("global::ConnectNet.ConnectJson.ExpectToken(ref reader, %s.StartObject);", tokens)
			p("while (reader.Read() && reader.TokenType != %s.EndObject)", tokens)
			p("{")
			p("var key = global::ConnectNet.ConnectJson.%s(ref reader);", jsonMapKeyReader(desc.MapKey().Kind()))
			p("reader.Read();")
			if !isValueMessage(desc.MapValue()) {
				p("global::ConnectNet.ConnectJson.RejectNull(ref reader);")
			}
			generateJSONAssign(p, desc.MapValue(), enumIndex, func(value string) string { return fmt.Sprintf("%s[key] = %s;", prop, value) })
			p("}")
		case desc.IsList():
			p("global::ConnectNet.ConnectJson.ExpectToken(ref reader, %s.StartArray);", tokens)
			p("while (reader.Read() && reader.TokenType != %s.EndArray)", tokens)
			p("{")
			if !isValueMessage(desc) {
				p("global::ConnectNet.ConnectJson.RejectNull(ref reader);")
			}
			generateJSONAssign(p, desc, enumIndex, func(value string) string { return fmt.Sprintf("%s.Add(%s);", prop, value) })
			p("}")
		default:
			generateJSONAssign(p, desc, enumIndex, func(value string) string { return fmt.Sprintf("%s = %s;", prop, value) })
		}
		p("continue;")
		p("}")
	}
	p("reader.Read();")
	p("reader.Skip();")
	p("}")
	p("}")
}

func isValueMessage(desc protoreflect.FieldDescriptor) bool {
	return desc.Message() != nil && desc.Message().FullName() == "google.protobuf.Value"
}

func jsonClear(field *protogen.Field) string {
	desc := field.Desc
	prop := "this." + propertyName(desc)
	switch {
	case desc.IsMap() || desc.IsList():
		return prop + ".Clear();"
	case desc.HasOptionalKeyword():
		return "this.Clear" + propertyName(desc) + "();"
	case field.Oneof != nil && !field.Oneof.Desc.IsSynthetic():
		oneof := underscoresToPascalCase(string(field.Oneof.Desc.Name()))
		return fmt.Sprintf("if (this.%sCase == %sOneofCase.%s) this.Clear%s();", oneof, oneof, oneofCaseName(desc), oneof)
	case desc.Message() != nil:
		return prop + " = null;"
	}
	switch desc.Kind() {
	case protoreflect.StringKind:
		return prop + " = \"\";"
	case protoreflect.BytesKind:
		return prop + " = global::Google.Protobuf.ByteString.Empty;"
	case protoreflect.BoolKind:
		return prop + " = false;"
	case protoreflect.EnumKind:
		return prop + " = default;"
	}
	return prop + " = 0;"
}

func generateJSONAssign(p func(string, ...interface{}), desc protoreflect.FieldDescriptor, enumIndex func(protoreflect.EnumDescriptor) int, assign func(string) string) {
	if desc.Kind() == protoreflect.EnumKind {
		// An unknown enum name is ignored, like any other unknown field.
		p("if (__ConnectJson.ReadEnum%d(ref reader, out var enumValue))", enumIndex(desc.Enum()))
		p("{")
		p("%s", assign("enumValue"))
		p("}")
		return
	}
	if desc.Message() != nil {
		if kind, wrapper := wrapperKinds[desc.Message().FullName()]; wrapper {
			p("%s", assign(jsonReadScalar(kind)))
			return
		}
		p("%s", assign(fmt.Sprintf("global::ConnectNet.ConnectJson.ReadMessage<%s>(ref reader, fallback)", csharpTypeName(desc.Message()))))
		return
	}
	p("%s", assign(jsonReadScalar(desc.Kind())))
}

func jsonReadScalar(kind protoreflect.Kind) string {
	name := map[protoreflect.Kind]string{
		protoreflect.BoolKind: "ReadBool", protoreflect.StringKind: "ReadString", protoreflect.BytesKind: "ReadBytes",
		protoreflect.FloatKind: "ReadFloat", protoreflect.DoubleKind: "ReadDouble",
		protoreflect.Int32Kind: "ReadInt32", protoreflect.Sint32Kind: "ReadInt32", protoreflect.Sfixed32Kind: "ReadInt32",
		protoreflect.Uint32Kind: "ReadUInt32", protoreflect.Fixed32Kind: "ReadUInt32",
		protoreflect.Int64Kind: "ReadInt64", protoreflect.Sint64Kind: "ReadInt64", protoreflect.Sfixed64Kind: "ReadInt64",
		protoreflect.Uint64Kind: "ReadUInt64", protoreflect.Fixed64Kind: "ReadUInt64",
	}[kind]
	return "global::ConnectNet.ConnectJson." + name + "(ref reader)"
}

func jsonMapKeyReader(kind protoreflect.Kind) string {
	switch kind {
	case protoreflect.StringKind:
		return "ReadString"
	case protoreflect.BoolKind:
		return "ReadBoolKey"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "ReadInt32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "ReadUInt32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "ReadInt64"
	}
	return "ReadUInt64"
}

func generateJSONEnumReader(p func(string, ...interface{}), index int, e protoreflect.EnumDescriptor) {
	const tokens = "global::System.Text.Json.JsonTokenType"
	typeName := csharpTypeName(e)
	values := e.Values()
	for i := 0; i < values.Len(); i++ {
		p("private static readonly global::System.Text.Json.JsonEncodedText E%d_%d = global::System.Text.Json.JsonEncodedText.Encode(%q);", index, i, string(values.Get(i).Name()))
	}
	p("internal static bool ReadEnum%d(ref global::System.Text.Json.Utf8JsonReader reader, out %s value)", index, typeName)
	p("{")
	p("if (reader.TokenType != %s.String)", tokens)
	p("{")
	p("value = (%s)global::ConnectNet.ConnectJson.ReadInt32(ref reader);", typeName)
	p("return true;")
	p("}")
	for i := 0; i < values.Len(); i++ {
		v := values.Get(i)
		p("if (global::ConnectNet.ConnectJson.TextEquals(ref reader, E%d_%d)) { value = (%s)%d; return true; }", index, i, typeName, v.Number())
	}
	p("value = default;")
	p("return false;")
	p("}")
}

func generateJSONEnumWriter(p func(string, ...interface{}), index int, e protoreflect.EnumDescriptor) {
	p("internal static void WriteEnum%d(global::System.Text.Json.Utf8JsonWriter writer, %s value)", index, csharpTypeName(e))
	p("{")
	p("switch ((int)value)")
	p("{")
	seen := map[protoreflect.EnumNumber]bool{}
	values := e.Values()
	for i := 0; i < values.Len(); i++ {
		v := values.Get(i)
		if seen[v.Number()] {
			continue
		}
		seen[v.Number()] = true
		p("case %d: writer.WriteStringValue(%q); break;", v.Number(), string(v.Name()))
	}
	p("default: writer.WriteNumberValue((int)value); break;")
	p("}")
	p("}")
}

func jsonPresence(field *protogen.Field) string {
	desc := field.Desc
	prop := "this." + propertyName(desc)
	switch {
	case desc.IsMap() || desc.IsList():
		return prop + ".Count != 0"
	case desc.HasOptionalKeyword():
		return "this.Has" + propertyName(desc)
	case field.Oneof != nil && !field.Oneof.Desc.IsSynthetic():
		oneof := underscoresToPascalCase(string(field.Oneof.Desc.Name()))
		return fmt.Sprintf("this.%sCase == %sOneofCase.%s", oneof, oneof, oneofCaseName(desc))
	case desc.Message() != nil:
		return prop + " != null"
	}
	switch desc.Kind() {
	case protoreflect.StringKind, protoreflect.BytesKind:
		return prop + ".Length != 0"
	case protoreflect.BoolKind:
		return prop
	case protoreflect.EnumKind:
		return "(int)" + prop + " != 0"
	}
	return prop + " != 0"
}

func jsonWriteValue(desc protoreflect.FieldDescriptor, expr string, enumIndex func(protoreflect.EnumDescriptor) int) string {
	if desc.Message() != nil {
		if kind, wrapper := wrapperKinds[desc.Message().FullName()]; wrapper {
			if kind != protoreflect.StringKind && kind != protoreflect.BytesKind {
				expr += ".Value"
			}
			return jsonWriteScalar(kind, expr)
		}
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteMessage(writer, %s, fallback);", expr)
	}
	if desc.Kind() == protoreflect.EnumKind {
		return fmt.Sprintf("__ConnectJson.WriteEnum%d(writer, %s);", enumIndex(desc.Enum()), expr)
	}
	return jsonWriteScalar(desc.Kind(), expr)
}

func jsonWriteScalar(kind protoreflect.Kind, expr string) string {
	switch kind {
	case protoreflect.BoolKind:
		return fmt.Sprintf("writer.WriteBooleanValue(%s);", expr)
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind, protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return fmt.Sprintf("writer.WriteNumberValue(%s);", expr)
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteInt64(writer, %s);", expr)
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteUInt64(writer, %s);", expr)
	case protoreflect.FloatKind:
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteFloat(writer, %s);", expr)
	case protoreflect.DoubleKind:
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteDouble(writer, %s);", expr)
	case protoreflect.StringKind:
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteString(writer, %s);", expr)
	case protoreflect.BytesKind:
		return fmt.Sprintf("global::ConnectNet.ConnectJson.WriteBytes(writer, %s);", expr)
	}
	panic(fmt.Sprintf("unexpected scalar kind %v", kind))
}

// The naming helpers below mirror protoc's C# generator (csharp_helpers.cc), because the
// partial classes emitted here must name the members it generates.

func underscoresToPascalCase(input string) string {
	var result strings.Builder
	capNext := true
	for _, c := range input {
		switch {
		case c >= 'a' && c <= 'z':
			if capNext {
				result.WriteRune(c - 'a' + 'A')
			} else {
				result.WriteRune(c)
			}
			capNext = false
		case c >= 'A' && c <= 'Z':
			result.WriteRune(c)
			capNext = false
		case c >= '0' && c <= '9':
			result.WriteRune(c)
			capNext = true
		default:
			capNext = true
		}
	}
	return result.String()
}

var reservedMemberNames = map[string]bool{
	"Types": true, "Descriptor": true, "Equals": true, "ToString": true, "GetHashCode": true,
	"WriteTo": true, "Clone": true, "CalculateSize": true, "MergeFrom": true, "OnConstruction": true, "Parser": true,
}

func propertyName(desc protoreflect.FieldDescriptor) string {
	name := underscoresToPascalCase(string(desc.Name()))
	if reservedMemberNames[name] {
		name += "_"
	}
	if name == string(desc.ContainingMessage().Name()) {
		name += "_"
	}
	return name
}

func oneofCaseName(desc protoreflect.FieldDescriptor) string {
	name := propertyName(desc)
	if name == "None" {
		return "None_"
	}
	return name
}

// csharpTypeName returns the fully qualified C# name of a message or enum, which may live in
// another file and therefore another namespace.
func csharpTypeName(desc protoreflect.Descriptor) string {
	name := string(desc.Name())
	for parent := desc.Parent(); parent != nil; parent = parent.Parent() {
		if _, isFile := parent.(protoreflect.FileDescriptor); isFile {
			break
		}
		name = string(parent.Name()) + ".Types." + name
	}
	if ns := getCSharpNamespace(desc.ParentFile()); ns != "" {
		return "global::" + ns + "." + name
	}
	return "global::" + name
}
